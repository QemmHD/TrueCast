"""Bundle the component styles in a fixed cascade for the static Pages app."""
from pathlib import Path
root=Path(__file__).resolve().parent.parent
parts=['style.css','atmosphere.css','observatory.css','horizon.css']
output='/* Generated by scripts/build-css.py. Edit the component styles, then rebuild. */\n'
for name in parts:
    output+=f'\n/* === {name} === */\n'+(root/name).read_text()+'\n'
(root/'app.css').write_text(output)
print(f'Bundled {len(parts)} style sources into app.css')
